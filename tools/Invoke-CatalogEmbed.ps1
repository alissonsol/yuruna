<#
.SYNOPSIS
    Copy the catalog kernel, the locale data and the default-locale message
    tables into every browser runtime that renders Yuruna text.
.DESCRIPTION
    A status page loads exactly one script. Anything the page needs in order to
    render its first label has to already be inside that script, or the label
    arrives after the paint that was supposed to show it -- and on the floor
    browser there is no module loader to arrange otherwise. So the kernel and
    the default locale are copied in, and only a reader who asks for a
    non-default language costs the page an extra request.

    Both runtimes get the same bytes from the same sources: the kernel from
    globalization/kernel, the tables from what the catalog compiler generated.
    Two copies of a file diverge the moment someone edits the near one, which
    is why -Check exists and why the suite runs it.

    Regenerating is safe to repeat: the block between the markers is replaced
    whole, so running twice leaves the same file.
.PARAMETER Check
    Report what would change and exit non-zero instead of writing. For the gate.
.PARAMETER Quiet
    Print only findings.
.EXAMPLE
    pwsh -File tools/Invoke-CatalogEmbed.ps1
.EXAMPLE
    pwsh -File tools/Invoke-CatalogEmbed.ps1 -Check
#>

[CmdletBinding(SupportsShouldProcess)]
param(
    [switch]$Check,
    [switch]$Quiet
)

$ErrorActionPreference = 'Stop'

$RepoRoot = Split-Path -Parent $PSScriptRoot
$KernelPath = Join-Path $RepoRoot 'globalization/kernel/yuruna.i18n.js'
$ManifestPath = Join-Path $RepoRoot 'globalization/locale-manifest.json'
$GeneratedBrowser = Join-Path $RepoRoot 'globalization/generated/browser'

$BeginMarker = '// >>> yuruna-i18n embedded block -- generated by tools/Invoke-CatalogEmbed.ps1'
$EndMarker = '// <<< yuruna-i18n embedded block'

# Which runtime carries which domains. A binary embeds only what its own pages
# render; a domain added here is bytes on every page that loads the runtime.
$Targets = @(
    @{ Path = 'test/status/yuruna.common.js'; Domains = @('status') }
    @{ Path = 'test/extension/extension-sdk/webui/assets/yuruna.core.js'; Domains = @('status') }
    # The pool domain rides pool-control's OWN script, not the shared runtime.
    # Every extension service loads the shared one, so a domain only one of
    # them renders would be bytes on every other service's pages for messages
    # none of them ask for.
    @{ Path = 'test/extension/pool-control-service/server/internal/httpsrv/web/assets/common.js'
       Domains = @('pool'); DomainsOnly = $true }
)

