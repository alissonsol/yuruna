$GoTargets = @(
    @{
        Module   = 'test/extension/pool-control-service/server'
        Package  = 'internal/catalog'
        Domains  = @('status', 'pool')
        Locales  = @('en-US', 'qps-Ploc', 'qps-Plocm')
    }
)

