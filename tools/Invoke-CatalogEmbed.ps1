# package that lives outside its own. Each consumer gets the compiled data
# copied in beside it instead, carrying only the domains that binary renders --
# a domain listed here is bytes in that service's image.
#
# The pseudo locales travel with the real one on purpose: the reference slice
# has to be answerable in expanded and mirrored pseudo, and a locale that is
