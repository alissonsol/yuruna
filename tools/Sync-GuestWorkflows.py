"""Regenerate Ubuntu entrypoints and their shared-workflow integrity pins."""
import argparse
import hashlib
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
version = (root / 'VERSION').read_text(encoding='ascii').strip()
if not re.fullmatch(r'\d{4}\.\d{2}\.\d{2}(?:\.\d+)?', version):
    raise SystemExit(f'Invalid VERSION: {version!r}')

generated = {}
for name in ('update', 'code', 'n8n', 'openclaw', 'postgresql'):
    body = root / f'guest/shared/ubuntu.{name}.sh'
    digest = hashlib.sha256(body.read_bytes()).hexdigest()
    text = f'''#!/bin/bash
# Version: {version}
# LICENSEURI https://yuruna.link/license
# Copyright (c) 2019-2026 by Alisson Sol et al.
# Generated by tools/Sync-GuestWorkflows.py; edit guest/shared/ubuntu.{name}.sh.
# --- REGION: Initialize environment
set -euo pipefail
workflow="guest/shared/ubuntu.{name}.sh"
expected="{digest}"
# --- REGION: Resolve shared workflow
if [ -n "${{BASH_SOURCE[0]:-}}" ] && [ -f "${{BASH_SOURCE[0]}}" ]; then
    local_workflow="$(dirname "${{BASH_SOURCE[0]}}")/../shared/ubuntu.{name}.sh"
    if [ -f "$local_workflow" ]; then
        actual=$(sha256sum "$local_workflow")
        [ "${{actual%% *}}" = "$expected" ] || {{ echo "Shared workflow checksum mismatch" >&2; exit 3; }}
        exec bash "$local_workflow" "$@"
    fi
fi
# --- REGION: Fetch shared workflow
# Reuse the installed fetcher's host discovery, pinned fallback, and digest gate.
export E_SHA="$expected" EXEC_SHA256="$expected" EXEC_REQUIRE_SHA256=1
exec /usr/local/lib/yuruna/fetch-and-execute.sh "$workflow" "$@"
'''
    for release in ('24', '26'):
        path = root / f'guest/ubuntu.server.{release}/ubuntu.server.{release}.{name}.sh'
        generated[path] = text.encode('utf-8')

if args.check:
    stale = [path for path, content in generated.items()
             if not path.is_file() or path.read_bytes() != content]
    if stale:
        raise SystemExit('Stale entrypoints:\n' + '\n'.join(str(path) for path in stale))
else:
    for path, content in generated.items():
        if not path.is_file() or path.read_bytes() != content:
            path.write_bytes(content)
